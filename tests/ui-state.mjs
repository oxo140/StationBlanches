import assert from "node:assert/strict";
import {stationView,offlineView} from "../web/state.js";
const base={engine:{ready:true},progress:{},present_results:[],pending:0,error:null};
assert.equal(stationView(base).kind,"ready");
assert.equal(stationView({...base,engine:{ready:false}}).kind,"blocked");
assert.equal(stationView({...base,error:"disk failed"}).kind,"error");
assert.equal(offlineView().kind,"offline");
const clean={verdict:"no_threat_detected",files:12,bytes:1024,threats:0,errors:0,quarantined:0};
assert.equal(stationView({...base,present_results:[clean]}).kind,"clean");
assert.equal(stationView({...base,present_results:[clean],pending:1}).kind,"scanning");
assert.equal(stationView({...base,present_results:[{...clean,errors:1}]}).kind,"incomplete");
assert.equal(stationView({...base,present_results:[{...clean,verdict:"interrupted"}]}).kind,"incomplete");
const infected={...clean,verdict:"infected",threats:1,quarantined:1};
assert.equal(stationView({...base,present_results:[clean,infected]}).kind,"infected");
assert.match(stationView({...base,present_results:[{...infected,quarantined:0}]}).message,/incomplète/);
assert.match(stationView({...base,present_results:[infected]}).message,/originaux restent/);
const progress={scan_id:"active",files:22,bytes:4096,threats:1,errors:0,quarantined:0,phase:"quarantine",current_file:"archive.zip"};
const view=stationView({...base,progress});
assert.equal(view.kind,"scanning");assert.equal(view.files,22);assert.equal(view.file,"archive.zip");assert.match(view.title,/quarantaine/);
console.log("Kiosk states, pending partitions, interrupted scans and quarantine reporting passed");
